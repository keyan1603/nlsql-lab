"""Generate setup/least_privilege.sql: narrow the reader account from 'SELECT on the whole database' to column-level grants
that leave out the two columns the policy never shows (salary_amt, natl_id).

    python scripts/make_least_privilege_sql.py

The file has to be run once by a MySQL administrator (for example: mysql -u root -p < setup/least_privilege.sql). It contains no passwords.
email_addr and phone_no stay readable at database level because the guard returns them masked, and masking is done in the query
the guard sends, so the account must be able to read the raw column. Protecting them in the database too would need a masked view.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from nlsql.config import ROOT                    # noqa: E402
from nlsql.schema_link import parse_schema       # noqa: E402

BLOCKED = {"salary_amt", "natl_id"}
ACCOUNT = "'nlsql_reader'@'localhost'"


def main() -> int:
    lines = ["-- Run once as a MySQL administrator. Narrows the reader from SELECT on every table to column-level grants",
             "-- that leave out salary_amt and natl_id. Generated by scripts/make_least_privilege_sql.py; contains no passwords.",
             "-- To undo: REVOKE SELECT ON nlsql_lab.* FROM 'nlsql_reader'@'localhost'; GRANT SELECT ON nlsql_lab.* TO 'nlsql_reader'@'localhost';",
             "", f"REVOKE SELECT ON nlsql_lab.* FROM {ACCOUNT};", ""]
    for t in parse_schema(True):
        names = [c.name for c in t.columns]
        if BLOCKED & set(names):
            cols = ", ".join(n for n in names if n not in BLOCKED)
            lines.append(f"GRANT SELECT ({cols}) ON nlsql_lab.{t.name} TO {ACCOUNT};")
        else:
            lines.append(f"GRANT SELECT ON nlsql_lab.{t.name} TO {ACCOUNT};")
    lines += ["", "FLUSH PRIVILEGES;", ""]
    (ROOT / "setup" / "least_privilege.sql").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
